fun themeSwatchColors(style: AppThemeStyle): List<Color> {
    val definition = themeDefinitions.firstOrNull { it.style == style } ?: defaultDefinition
    val colors = definition.marketColors
    return listOf(
        definition.colorScheme.surface,
        colors.bullishSubdued,
        colors.bearishSubdued,
    )
}

@Composable
fun StockTheme(
    style: AppThemeStyle = AppThemeStyle.TUSHENG,
    content: @Composable () -> Unit,
) {
    val definition = themeDefinitions.firstOrNull { it.style == style } ?: defaultDefinition
    androidx.compose.runtime.CompositionLocalProvider(
        LocalMarketColors provides definition.marketColors,
        LocalIsDarkTheme provides definition.isDark,
    ) {
        MaterialTheme(
            colorScheme = definition.colorScheme,
            content = content,
        )
    }
}
