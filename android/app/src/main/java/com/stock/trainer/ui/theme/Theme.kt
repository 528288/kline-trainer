/**
 * 主题体系（pll-ui C1 三层：原始色阶 → 语义色 → 组件默认值）
 *
 * 本轮优化约束（全部由脚本实测，见 _audit_stock/verify_themes.py）：
 *   正文/次要正文 ≥ 4.5:1；弱化/禁用/主色文字 ≥ 3:1；白字压填充 ≥ 4.5:1
 * 涨跌语义色拆成三层，避免"又当文字又当按钮底"的对比度冲突：
 *   bullish / bearish            → 文字与数字（压在 surface 上 ≥4.5:1）
 *   bullishFill / bearishFill    → 按钮填充（白字压上去 ≥4.5:1）
 *   bullishSubdued / bearishSubdued → K 线柱色（≥3:1，保留原品牌观感）
 */
