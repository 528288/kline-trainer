private val defaultDefinition = themeDefinitions.first()

val AppThemeStyles: List<AppThemeStyle> = themeDefinitions.map { it.style }

val LocalMarketColors = staticCompositionLocalOf { defaultDefinition.marketColors }

val LocalIsDarkTheme = staticCompositionLocalOf { defaultDefinition.isDark }

val AccentRed: Color
    @Composable get() = LocalMarketColors.current.bullish

val AccentGreen: Color
    @Composable get() = LocalMarketColors.current.bearish

val GoldAccent: Color
    @Composable get() = LocalMarketColors.current.warning

fun themeStyleFromId(id: String?): AppThemeStyle {
    return AppThemeStyles.firstOrNull { it.id == id } ?: AppThemeStyle.TUSHENG
}

